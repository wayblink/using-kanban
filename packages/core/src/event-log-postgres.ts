/**
 * PostgreSQL-backed event log for the shared server.
 *
 * Same contract as SQLite/JSONL: an append-only sequence of events, plus a
 * separate card sequence so a card's handle does not inflate with its edit
 * history. Postgres is here for the server deployment — one durable store,
 * standard backups, and no native addon in the image — not to change the
 * engine's semantics.
 *
 * The card sequence is a one-row table rather than an identity column: the
 * allocation has to be seeded above whatever card ids the log already carries,
 * and it must be serialised with the append transaction, exactly like SQLite's
 * `card_seq`.
 */
import pg from "pg";
import type { PoolClient, QueryResultRow } from "pg";
import { EventRowSchema, StoredEventSchema } from "./schemas.js";
import type { Event, EventType, NewEvent } from "./types.js";
import type { EventLog } from "./event-log.js";
import { KanbanError } from "./errors.js";

const { Pool } = pg;

const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS events (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts         TEXT    NOT NULL,
  actor_type TEXT    NOT NULL,
  actor_name TEXT    NOT NULL,
  source     TEXT    NOT NULL,
  type       TEXT    NOT NULL,
  card_id    BIGINT  NOT NULL,
  payload    JSONB   NOT NULL
);
CREATE INDEX IF NOT EXISTS events_card_id_idx ON events (card_id);
CREATE SEQUENCE IF NOT EXISTS ukb_card_seq AS BIGINT;
CREATE TABLE IF NOT EXISTS ukb_schema (
  version INTEGER PRIMARY KEY
);
INSERT INTO ukb_schema (version) VALUES (1) ON CONFLICT DO NOTHING;
`;

export interface PgEventLogOptions {
  /** `postgres://user:pass@host:5432/db` */
  readonly connectionString: string;
  /** Pool size. A single ukb server needs very few connections. */
  readonly maxConnections?: number | undefined;
}

export interface ImportResult {
  readonly events: number;
  readonly maxEventId: number;
  readonly maxCardId: number;
}

export class PgEventLog implements EventLog {
  private readonly pool: pg.Pool;
  private readonly ready: Promise<void>;

  constructor(options: PgEventLogOptions) {
    if (options.connectionString.trim() === "") {
      throw new KanbanError(
        "invalid_input",
        "postgres storage needs a connection URL (UKB_PG_URL or DATABASE_URL)",
      );
    }
    this.pool = new Pool({
      connectionString: options.connectionString,
      max: options.maxConnections ?? 4,
    });
    this.ready = this.initialize();
    // Keep an unawaited initialization from surfacing as an unhandled rejection;
    // every method still awaits the same promise and sees the error.
    this.ready.catch(() => undefined);
  }

  private async initialize(): Promise<void> {
    const client = await this.pool.connect();
    try {
      await client.query(SCHEMA_SQL);
      await this.syncCardSequence(client);
    } finally {
      client.release();
    }
  }

  /**
   * Point the card sequence at the highest card id the log already carries.
   *
   * A sequence never moves backwards: after a restart the counter may already
   * be ahead of the visible maximum (the highest card could have been deleted),
   * and reusing that number would hand a human a handle that once existed.
   */
  private async syncCardSequence(client: PoolClient): Promise<void> {
    await client.query(`
      WITH state AS (
        SELECT COALESCE((SELECT MAX(card_id) FROM events), 0) AS max_card,
               (SELECT is_called FROM ukb_card_seq) AS called,
               (SELECT last_value FROM ukb_card_seq) AS seq_last
      )
      SELECT setval(
        'ukb_card_seq',
        GREATEST(max_card, CASE WHEN called THEN seq_last ELSE 0 END, 1),
        GREATEST(max_card, CASE WHEN called THEN seq_last ELSE 0 END) > 0
      )
      FROM state
    `);
  }

  async append(rows: readonly NewEvent[]): Promise<Event[]> {
    await this.ready;
    if (rows.length === 0) return [];
    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");

      const stored: Event[] = [];
      for (const row of rows) {
        const ts = new Date().toISOString();
        const cardId =
          row.cardId === null || row.cardId === undefined
            ? await this.nextCardId(client)
            : row.cardId;
        const inserted = await client.query<{ id: string }>(
          `INSERT INTO events (ts, actor_type, actor_name, source, type, card_id, payload)
           VALUES ($1, $2, $3, $4, $5, $6, $7::jsonb)
           RETURNING id`,
          [
            ts,
            row.actor.type,
            row.actor.name,
            row.source,
            row.type,
            cardId,
            JSON.stringify(row.payload),
          ],
        );
        const id = Number(inserted.rows[0]?.id);
        stored.push({
          id,
          ts,
          actor: row.actor,
          source: row.source,
          type: row.type,
          cardId,
          payload: row.payload,
        });
      }
      await client.query("COMMIT");
      return stored;
    } catch (error) {
      await client.query("ROLLBACK").catch(() => undefined);
      throw error;
    } finally {
      client.release();
    }
  }

  private async nextCardId(client: PoolClient): Promise<number> {
    // `nextval` is atomic across connections; no table lock is involved.
    const result = await client.query<{ id: string }>(
      `SELECT nextval('ukb_card_seq')::text AS id`,
    );
    return Number(result.rows[0]?.id);
  }

  async since(id: number): Promise<Event[]> {
    await this.ready;
    const result = await this.pool.query<QueryResultRow>(
      `SELECT id, ts, actor_type, actor_name, source, type, card_id, payload
       FROM events WHERE id > $1 ORDER BY id ASC`,
      [id],
    );
    return result.rows.map((row) => toEvent(row));
  }

  async byCard(cardId: number): Promise<Event[]> {
    await this.ready;
    const result = await this.pool.query<QueryResultRow>(
      `SELECT id, ts, actor_type, actor_name, source, type, card_id, payload
       FROM events WHERE card_id = $1 ORDER BY id ASC`,
      [cardId],
    );
    return result.rows.map((row) => toEvent(row));
  }

  async maxId(): Promise<number> {
    await this.ready;
    const result = await this.pool.query<{ max_id: string | null }>(
      `SELECT COALESCE(MAX(id), 0)::text AS max_id FROM events`,
    );
    return Number(result.rows[0]?.max_id ?? 0);
  }

  /**
   * Copies events in with their existing ids.
   *
   * Used by `ukb migrate --to postgres`: event ids and card ids are the wire
   * identity of a board (card handles are typed by humans), so migration must
   * preserve both and then move both sequences past the imported maximum.
   */
  async importEvents(
    events: readonly Event[],
    options: { readonly force?: boolean | undefined } = {},
  ): Promise<ImportResult> {
    await this.ready;
    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");
      const existing = await client.query<{ count: string }>(
        `SELECT COUNT(*)::text AS count FROM events`,
      );
      if (Number(existing.rows[0]?.count ?? 0) > 0 && options.force !== true) {
        throw new KanbanError(
          "invalid_input",
          "the target database already has events — pass --force to import anyway",
        );
      }
      for (const event of events) {
        await client.query(
          `INSERT INTO events (id, ts, actor_type, actor_name, source, type, card_id, payload)
           VALUES ($1, $2, $3, $4, $5, $6, $7, $8::jsonb)
           ON CONFLICT (id) DO NOTHING`,
          [
            event.id,
            event.ts,
            event.actor.type,
            event.actor.name,
            event.source,
            event.type,
            event.cardId,
            JSON.stringify(event.payload),
          ],
        );
      }
      // Explicit ids do not advance an identity sequence; move it past the
      // highest imported value so the next live append cannot collide.
      await client.query(
        `SELECT setval(
           pg_get_serial_sequence('events', 'id'),
           GREATEST((SELECT COALESCE(MAX(id), 0) FROM events), 1),
           (SELECT COALESCE(MAX(id), 0) FROM events) > 0
         )`,
      );
      await this.syncCardSequence(client);

      const summary = await client.query<{
        events: string;
        max_event: string;
        max_card: string;
      }>(
        `SELECT COUNT(*)::text AS events,
                COALESCE(MAX(id), 0)::text AS max_event,
                COALESCE(MAX(card_id), 0)::text AS max_card
         FROM events`,
      );
      await client.query("COMMIT");
      return {
        events: Number(summary.rows[0]?.events ?? 0),
        maxEventId: Number(summary.rows[0]?.max_event ?? 0),
        maxCardId: Number(summary.rows[0]?.max_card ?? 0),
      };
    } catch (error) {
      await client.query("ROLLBACK").catch(() => undefined);
      throw error;
    } finally {
      client.release();
    }
  }

  close(): void {
    // The interface is synchronous; let the pool drain in the background.
    void this.end();
  }

  /** Awaitable shutdown for callers that need the sockets closed (tests, graceful stop). */
  async end(): Promise<void> {
    await this.pool.end().catch(() => undefined);
  }
}

function toEvent(row: QueryResultRow): Event {
  const parsed = EventRowSchema.parse({
    id: Number(row.id),
    ts: row.ts,
    actor_type: row.actor_type,
    actor_name: row.actor_name,
    source: row.source,
    type: row.type,
    card_id: Number(row.card_id),
    payload:
      typeof row.payload === "string"
        ? row.payload
        : JSON.stringify(row.payload),
  });
  const payload = JSON.parse(parsed.payload) as unknown;
  if (
    payload === null ||
    typeof payload !== "object" ||
    Array.isArray(payload)
  ) {
    throw new Error(`event ${parsed.id} has a non-object payload`);
  }
  const stored = StoredEventSchema.parse({
    id: parsed.id,
    ts: parsed.ts,
    actor: { type: parsed.actor_type, name: parsed.actor_name },
    source: parsed.source,
    type: parsed.type,
    cardId: parsed.card_id,
    payload,
  });
  return {
    id: stored.id,
    ts: stored.ts,
    actor: stored.actor,
    source: stored.source,
    type: stored.type as EventType,
    cardId: stored.cardId,
    payload: stored.payload,
  };
}
